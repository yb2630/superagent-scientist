#!/usr/bin/env python3
"""Generate the deterministic test vectors committed under tests/data/.

The vectors are produced by the independent reference model in
tools/tilecpp_reference.py.  They are plain text so that the C++ tests need no
JSON dependency and code review can read them.

Usage:
    python3 tools/generate_test_vectors.py
"""

from __future__ import annotations

import math
import random
import sys
from fractions import Fraction
from pathlib import Path

TOOLS_DIR = Path(__file__).resolve().parent
REPO_ROOT = TOOLS_DIR.parent
DATA_DIR = REPO_ROOT / "tests" / "data"
sys.path.insert(0, str(TOOLS_DIR))

import tilecpp_reference as ref  # noqa: E402


def float_token(value: float) -> str:
    if math.isnan(value):
        return "nan"
    return f"{ref.f32_bits(ref.f32(value)):08x}"


def write_decode_vectors() -> None:
    lines = [
        "# TileCpp reference vectors: E4M3FN decoding of all 256 bit patterns.",
        "# Generated by tools/generate_test_vectors.py; do not edit by hand.",
        "# Columns: e4m3_bits_hex decoded_float32_bits_hex (or 'nan')",
    ]
    for code in range(256):
        lines.append(f"{code:02x} {float_token(ref.decode(code))}")
    (DATA_DIR / "fp8_decode.tsv").write_text("\n".join(lines) + "\n",
                                             encoding="utf-8")


def encode_vectors():
    values = []
    seen_bits = set()

    def add(value: float) -> None:
        if math.isnan(value):
            bits = 0x7FC00000
        elif math.isinf(value):
            bits = ref.f32_bits(value)
        else:
            bits = ref.f32_bits(ref.f32(value))
        if bits not in seen_bits:
            seen_bits.add(bits)
            values.append(ref.bits_to_f32(bits))

    add(0.0)
    add(-0.0)

    # Every representable magnitude, both signs.
    for code in range(0x7F):
        magnitude = ref.decode(code)
        add(magnitude)
        add(-magnitude)

    # Rounding boundaries: every midpoint between adjacent finite magnitudes is
    # exactly representable as float32; include the tie and its two neighbours.
    magnitudes = ref.FINITE_MAGNITUDES
    for code in range(0x7E):
        midpoint = (magnitudes[code] + magnitudes[code + 1]) / 2
        midpoint_f32 = ref.f32(float(midpoint))
        if Fraction(midpoint_f32) != midpoint:
            raise AssertionError(f"midpoint {midpoint} is not a float32")
        bits = ref.f32_bits(midpoint_f32)
        for offset in (-1, 0, 1):
            for sign in (0, 0x80000000):
                add(ref.bits_to_f32(bits | sign) if offset == 0
                    else ref.bits_to_f32((bits + offset) | sign))

    # Saturation and special values.
    for value in (
        448.0,
        math.nextafter(448.0, math.inf),
        448.5,
        464.0,
        465.0,
        1e30,
        3.4028234663852886e38,
        math.inf,
        -math.inf,
        math.nan,
    ):
        add(value)

    # Deterministic pseudo-random finite float32 values.
    rng = random.Random(20261113)
    while len(values) < 1200:
        bits = rng.getrandbits(32)
        value = ref.bits_to_f32(bits)
        if math.isfinite(value):
            add(value)

    values.sort(key=ref.f32_bits)
    lines = [
        "# TileCpp reference vectors: E4M3FN encoding.",
        "# Generated by tools/generate_test_vectors.py; do not edit by hand.",
        "# Columns: input_float32_bits_hex expected_e4m3_bits_hex",
        "# Includes every representable value, every rounding midpoint and its",
        "# float32 neighbours, saturation/special values and seeded random values.",
    ]
    for value in values:
        if math.isnan(value):
            input_bits = ref.f32_bits(value)
        else:
            input_bits = ref.f32_bits(ref.f32(value))
        lines.append(f"{input_bits:08x} {ref.encode(value):02x}")
    (DATA_DIR / "fp8_encode.tsv").write_text("\n".join(lines) + "\n",
                                             encoding="utf-8")


def random_values(rng, count):
    values = []
    for _ in range(count):
        kind = rng.random()
        if kind < 0.08:
            value = 0.0
        elif kind < 0.16:
            value = rng.uniform(-1e-7, 1e-7)
        elif kind < 0.24:
            value = rng.uniform(-1e7, 1e7)
        else:
            value = rng.uniform(-4.0, 4.0)
        values.append(ref.f32(value))
    return values


def random_case(rng, rows, columns, input_stride, padding):
    values = []
    for _ in range(rows):
        values.extend(random_values(rng, columns))
        values.extend([ref.f32(padding)] * (input_stride - columns))
    return values


def quantize_cases():
    rng = random.Random(49952026)
    cases = []

    def add(name, rows, columns, input_stride, output_stride, values):
        assert len(values) == rows * input_stride, (name, len(values))
        converted = [v if math.isnan(v) else ref.f32(v) for v in values]
        cases.append({
            "name": name,
            "rows": rows,
            "columns": columns,
            "input_stride": input_stride,
            "output_stride": output_stride,
            "values": converted,
        })

    add("single-zero", 1, 1, 1, 1, [0.0])
    add("single-one", 1, 1, 1, 1, [1.0])
    add("signed-zero", 1, 2, 2, 4, [-0.0, 0.0])
    add("basic", 2, 3, 3, 5,
        [0.0, 1.0, -1.0, 0.5, -0.25, 2.0])

    padded_rows = [
        [1.0, -2.0, 0.5, 0.0, 3.0],
        [1e-3, 2e-3, -3e-3, 4e-3, 5e-3],
        [100.0, -200.0, 300.0, -400.0, 448.0],
    ]
    padded = []
    for row in padded_rows:
        padded.extend(ref.f32(v) for v in row)
        padded.extend([ref.f32(1e20)] * 2)  # padding must not influence scales
    add("padded", 3, 5, 7, 6, padded)

    for name, rows, columns, input_stride, output_stride in (
        ("random-small", 4, 8, 10, 12),
        ("random-medium", 5, 7, 8, 7),
        ("random-wide", 2, 17, 20, 17),
        ("random-column", 3, 1, 1, 3),
    ):
        values = random_case(rng, rows, columns, input_stride, 1e20)
        add(name, rows, columns, input_stride, output_stride, values)

    denorm = ref.E4M3_DENORM_MIN
    special = [
        [0.0, 0.0, 0.0, 0.0],
        [math.nan, math.inf, -math.inf, 1.0],
        [denorm, -denorm, 2 * denorm, 0.0],
    ]
    special_values = []
    for row in special:
        special_values.extend(row)
        special_values.append(ref.f32(1e20))
    add("special-values", 3, 4, 5, 4, special_values)

    add("extreme", 2, 4, 4, 6,
        [448.0, -448.0, 1e30, -1e-30,
         3.4028234663852886e38, -3.4028234663852886e38, 0.0, -0.0])

    tiny = [denorm, 0.0, -denorm, 2 * denorm] + [ref.f32(1e20)] * 4
    add("tiny", 1, 4, 8, 5, tiny)

    add("rounding", 2, 6, 6, 6,
        [447.9, 448.0, 448.1, -300.3, 0.1, 1e-8,
         1.0, 1.0009765625, 0.99951171875, -1.5, 2.25, 3.375])

    spread = []
    for _ in range(3):
        for _ in range(6):
            spread.append(ref.f32(rng.uniform(-1.0, 1.0) *
                                  (10.0 ** rng.randint(-20, 20))))
        spread.extend([ref.f32(1e20)] * 3)
    add("random-spread", 3, 6, 9, 7, spread)

    return cases


def write_quantize_vectors() -> None:
    lines = [
        "# TileCpp reference vectors: per-row E4M3FN quantization.",
        "# Generated by tools/generate_test_vectors.py; do not edit by hand.",
        "# Format per case:",
        "#   case <rows> <columns> <input_stride> <output_stride>",
        "#   in <rows*input_stride float32 bits, row-major, padding included>",
        "#   scales <rows float32 scale bits>",
        "#   quantized <rows*columns E4M3 bytes>",
        "#   dequantized <rows*columns float32 bits (or nan)>",
        "#   end",
    ]
    for case in quantize_cases():
        rows = case["rows"]
        columns = case["columns"]
        input_stride = case["input_stride"]
        output_stride = case["output_stride"]
        values = case["values"]
        scales, quantized, dequantized = ref.quantize_rows(
            values, rows, columns, input_stride)
        lines.append("")
        lines.append(f"# case: {case['name']}")
        lines.append(
            f"case {rows} {columns} {input_stride} {output_stride}")
        lines.append("in " + " ".join(float_token(v) for v in values))
        lines.append("scales " + " ".join(float_token(v) for v in scales))
        lines.append("quantized " + " ".join(
            f"{code:02x}" for row in quantized for code in row))
        lines.append("dequantized " + " ".join(
            float_token(v) for row in dequantized for v in row))
        lines.append("end")
    (DATA_DIR / "quantize.tsv").write_text("\n".join(lines) + "\n",
                                           encoding="utf-8")


def main() -> int:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    write_decode_vectors()
    encode_vectors()
    write_quantize_vectors()
    print(f"Wrote reference vectors to {DATA_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
